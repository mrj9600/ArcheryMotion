// Writes src/app/build-info.ts with the version being built: the number of commits
// (rises with every change), the short commit hash and the commit date.
// Run by the deploy workflow before `ng build`; locally the file says "dev".
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const git = (args) => execSync(`git ${args}`, { encoding: 'utf8' }).trim();
const info = {
  build: Number(git('rev-list --count HEAD')),
  commit: git('rev-parse --short HEAD'),
  date: git('log -1 --format=%cI'),
};
writeFileSync(
  new URL('../src/app/build-info.ts', import.meta.url),
  `// Generated by tools/build-info.mjs\nimport { BuildInfo } from './build-info.model';\n\nexport const BUILD_INFO: BuildInfo = ${JSON.stringify(info, null, 2)};\n`,
);
console.log('Build info', info);
